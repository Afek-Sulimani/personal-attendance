import LoadingIndicator from "../components/LoadingIndicator";
import { useState } from "react";
import type { FormEvent } from "react";
import { Link } from "react-router-dom";
import AuthLayout from "../components/AuthLayout";
import CopyableValue from "../components/CopyableValue";
import { registerCompany } from "../features/companies/companyRegistrationApi";
import type { CompanyRegistrationResult } from "../features/companies/companyRegistrationApi";

export default function CompanyRegistrationPage() {
  const [companyName, setCompanyName] = useState("");
  const [companyRepresentativeName, setCompanyRepresentativeName] = useState("");
  const [companyRepresentativeEmail, setCompanyRepresentativeEmail] = useState("");
  const [registration, setRegistration] = useState<CompanyRegistrationResult | null>(null);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [errorMessage, setErrorMessage] = useState("");

  async function handleSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    setErrorMessage("");
    setIsSubmitting(true);

    try {
      const result = await registerCompany({
        companyName,
        companyRepresentativeName,
        companyRepresentativeEmail,
      });
      setRegistration(result);
    } catch (error) {
      setErrorMessage(error instanceof Error ? error.message : "Company registration could not be completed.");
    } finally {
      setIsSubmitting(false);
    }
  }

  return (
    <AuthLayout scrollable>
      <div className="auth-heading">
        <p className="auth-eyebrow">COMPANY SETUP</p>
        <h1>{registration ? "Company created" : "Register a company"}</h1>
        <p className="auth-description">
          {registration
            ? "Share the activation link with the company representative to finish setting up access."
            : "Create a company and invite its first company representative."}
        </p>
      </div>

      {errorMessage && <div className="status-banner error" role="alert">{errorMessage}</div>}

      {!registration ? (
        <form className="auth-form company-registration-form" onSubmit={event => void handleSubmit(event)}>
          <div className="form-field">
            <label htmlFor="company-name">Company name</label>
            <input
              id="company-name"
              name="companyName"
              type="text"
              autoComplete="organization"
              value={companyName}
              onChange={event => setCompanyName(event.target.value)}
              required
              maxLength={200}
              placeholder="Enter the company name"
            />
          </div>

          <div className="form-field">
            <label htmlFor="company-representative-name">Company representative name</label>
            <input
              id="company-representative-name"
              name="companyRepresentativeName"
              type="text"
              autoComplete="name"
              value={companyRepresentativeName}
              onChange={event => setCompanyRepresentativeName(event.target.value)}
              required
              maxLength={200}
              placeholder="Enter the contact's name"
            />
          </div>

          <div className="form-field">
            <label htmlFor="company-representative-email">Company representative email</label>
            <input
              id="company-representative-email"
              name="companyRepresentativeEmail"
              type="email"
              autoComplete="email"
              value={companyRepresentativeEmail}
              onChange={event => setCompanyRepresentativeEmail(event.target.value)}
              required
              maxLength={256}
              placeholder="name@company.com"
            />
          </div>

          <p className="field-hint">
            The company ID is generated by the system. The company representative will choose a password from the activation link.
          </p>
          <button aria-busy={isSubmitting} className="primary-button" type="submit" disabled={isSubmitting}>
            {isSubmitting ? <LoadingIndicator label="Creating company…" /> : "Create company"}
          </button>
        </form>
      ) : (
        <section className="registration-result" aria-label="Company registration result">
          <div className="status-banner success" role="status">
            Company created. We recommend setting up key roles, such as HR and Payroll, to support a well-organized company.
          </div>
          <div className="registration-value">
            <p className="registration-value-label">Company ID</p>
            <p className="registration-value-content">{registration.companyCode}</p>
          </div>
          <div className="registration-value">
            <p className="registration-value-label">Company representative email</p>
            <p className="registration-value-content">{registration.companyRepresentativeEmail}</p>
          </div>
          <CopyableValue
            label="Activation link"
            value={registration.activationUrl}
            displayText="Temporary link to activate a company representative account"
          />
          <p className="registration-expiry">
            The activation link expires 48 hours.
          </p>
        </section>
      )}

      <p className="auth-note">
        <Link to="/login">Return to sign in</Link>
      </p>
    </AuthLayout>
  );
}
